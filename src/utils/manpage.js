// backdrop(1) and backdrop-config(5) in roff, made from the program's own command tree and the config schema so
// they cannot drift from the CLI. `backdrop man` prints them; `npm run man` writes share/man (checked by
// test/utils/manpage.test.js). Prose that the code cannot say (description, files, examples) lives here.

// Text for roff: backslashes and hyphens escaped, and a line that would start with a control character guarded
export function roff(text) {
  return String(text ?? '')
    .replace(/\\/g, '\\e')
    .replace(/-/g, '\\-')
    .split('\n')
    .map(line => (/^[.']/.test(line) ? `\\&${line}` : line))
    .join('\n');
}

const bold = text => `\\fB${roff(text)}\\fR`;
const italic = text => `\\fI${roff(text)}\\fR`;

// Paths of the machine the page was made on never reach it
function portable(text) {
  const home = os.homedir();
  return home && home !== '/' ? String(text).split(home).join('~') : String(text);
}

function header(name, section, { version, date }) {
  return [
    `.\\" Generated by backdrop ${version} (src/utils/manpage.js); edit that file, then run npm run man.`,
    `.TH ${name.toUpperCase()} ${section} "${date ?? ''}" "backdrop ${version}" "${section === 5 ? 'File Formats' : 'User Commands'}"`
  ];
}

const paragraphs = text => text.trim().split(/\n\s*\n/).flatMap(block => ['.PP', roff(block.replace(/\s*\n\s*/g, ' '))]);

// "-m, --monitor <name>" with the flags bold and the value italic
function formatFlags(flags) {
  return flags.split(/(\s*,\s*|\s+)/).map(part => {
    if (/^\s*,\s*$/.test(part)) return ', ';
    if (/^\s+$/.test(part)) return ' ';
    if (/^[<[]/.test(part)) return italic(part);
    return bold(part);
  }).join('');
}

function argumentText(argument) {
  const name = `${argument.name()}${argument.variadic ? '...' : ''}`;
  return argument.required ? `<${name}>` : `[${name}]`;
}

function describeOption(option) {
  const extra = [];
  if (option.argChoices?.length) extra.push(`one of ${option.argChoices.join(', ')}`);
  if (option.defaultValue !== undefined && option.defaultValue !== false) extra.push(`default ${portable(JSON.stringify(option.defaultValue))}`);
  return `${option.description ?? ''}${extra.length ? ` (${extra.join('; ')})` : ''}`;
}

function commandSection(command) {
  const args = command.registeredArguments.map(argumentText);
  const options = command.options.filter(option => !option.hidden);
  const lines = ['.TP', [bold(command.name()), options.length ? `[${italic('options')}]` : null, ...args.map(italic)].filter(Boolean).join(' '),
    roff(portable(command.description()))];
  const described = command.registeredArguments.filter(argument => argument.description);
  if (described.length || options.length) lines.push('.RS');
  for (const argument of described) lines.push('.TP', italic(argumentText(argument)), roff(portable(argument.description)));
  for (const option of options) lines.push('.TP', formatFlags(option.flags), roff(portable(describeOption(option))));
  if (described.length || options.length) lines.push('.RE');
  return lines;
}

