function valueAt(object, keys) {
  return keys.reduce((value, key) => (value && typeof value === 'object' ? value[key] : undefined), object);
}

// backdrop-config(5) from the schema's fields (configFields) and the defaults (ConfigManager.getUserDefaults)
export function configPage(fields, defaults, { version, date } = {}) {
  const sections = new Map();
  for (const field of fields) {
    const section = field.keys[0];
    if (!sections.has(section)) sections.set(section, []);
    sections.get(section).push(field);
  }
  const fieldLines = field => {
    const details = [KIND_NAMES[field.kind] ?? field.kind, `default ${bold(formatValue(valueAt(defaults, field.keys)))}`];
    if (field.choices?.length) details.push(`one of ${field.choices.join(', ')}`);
    return ['.TP', `${bold(field.key)} (${details.join(', ')})`, roff(portable(field.help ?? ''))];
  };
  const visualizer = defaults.visualizer && typeof defaults.visualizer === 'object'
    ? Object.entries(defaults.visualizer).filter(([key]) => key !== 'presets').flatMap(([key, value]) => {
      const shown = value && typeof value === 'object' && !Array.isArray(value) ? 'a mapping' : formatValue(value);
      return ['.TP', `${bold(`visualizer.${key}`)} (default ${bold(Array.isArray(value) && value.length > 3 ? `${value.length} entries` : shown)})`];
    })
    : [];
  return [
    ...header('backdrop-config', 5, { version, date }),
    '.SH NAME',
    'backdrop-config \\- the configuration file of backdrop',
    '.SH SYNOPSIS',
    italic('$XDG_CONFIG_HOME/backdrop/config.yaml'),
    '.SH DESCRIPTION',
    ...paragraphs(CONFIG_DESCRIPTION),
    ...[...sections].flatMap(([section, list]) => [
      `.SH ${section.toUpperCase()}`,
      ...(SECTION_NOTES[section] ? [roff(SECTION_NOTES[section])] : []),
      ...list.flatMap(fieldLines)
    ]),
    '.SH VISUALIZER',
    roff(SECTION_NOTES.visualizer),
    ...visualizer,
    '.SH PATHS',
    roff('Where backdrop keeps its files. They default to XDG locations and are not written to the file; set one to move it.'),
    ...PATHS.flatMap(([key, value]) => ['.TP', bold(key), italic(value)]),
    '.SH SEE ALSO',
    `${bold('backdrop')}(1); config.example.yaml and docs/specs/config.md in the source tree`,
    ''
  ].join('\n');
}

// The release date of version in CHANGELOG.md, so the page changes with a release rather than every day
export function releaseDate(version, changelog = new URL('../../CHANGELOG.md', import.meta.url)) {
  try {
    const text = fs.readFileSync(changelog, 'utf8');
    const escaped = version.replace(/[.]/g, '\\.');
    return new RegExp(`^## \\[${escaped}\\] - (\\d{4}-\\d{2}-\\d{2})`, 'm').exec(text)?.[1] ?? '';
  } catch {
    return '';
  }
}

export function manPage(section, program, version) {
  const date = releaseDate(version);
  if (String(section) === '5') return configPage(configFields(), new ConfigManager('/nonexistent/config.yaml').getUserDefaults(), { version, date });
  if (String(section) === '1') return commandPage(program, { version, date });
  throw new Error(`No man page in section ${section}; 1 is backdrop(1), 5 is backdrop-config(5)`);
}

export function printManPage(section, program, version) {
  process.stdout.write(manPage(section, program, version));
}
