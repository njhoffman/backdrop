import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ENTRY_POINT = fileURLToPath(new URL('../index.js', import.meta.url));

// A word in a unit file: quoted for ExecStart, % doubled so systemd does not expand specifiers
function quote(text) {
  return `"${String(text).replace(/%/g, '%%').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function onPath(name, searchPath) {
  return (searchPath ?? '').split(':').filter(Boolean).some(dir => {
    try {
      fs.accessSync(path.join(dir, name), fs.constants.X_OK);
      return true;
    } catch {
      return false;
    }
  });
}

// Prints a systemd user unit running the daemon. The PATH of the shell that generated it is written in:
// user services do not see a login shell's PATH, so node from nvm or pnpm, or tools under ~/.local/bin,
// would not be found otherwise. node is then started through that PATH, so a version manager's shim keeps
// working across node upgrades; without node on it, the absolute path of the running node is used.
export class SystemdCommand {
  constructor(config, database, logger, { execPath = process.execPath, entryPoint = ENTRY_POINT, env = process.env } = {}) {
    this.execPath = execPath;
    this.entryPoint = entryPoint;
    this.env = env;
  }

  generate(version) {
    const searchPath = this.env.PATH;
    const environment = searchPath ? `Environment=${quote(`PATH=${searchPath}`)}\n` : '';
    const node = onPath('node', searchPath) ? '/usr/bin/env node' : quote(this.execPath);
    return `# backdrop ${version} daemon as a systemd user service, generated by \`backdrop systemd\`.
# Regenerate after moving node or backdrop. Install and enable with:
#   backdrop systemd > ~/.config/systemd/user/backdrop.service
#   systemctl --user daemon-reload && systemctl --user enable backdrop
# It needs DISPLAY and XAUTHORITY. i3 does not start graphical-session.target, so start it from i3 with:
#   exec --no-startup-id systemctl --user import-environment DISPLAY XAUTHORITY && systemctl --user start backdrop
# Logs: journalctl --user -u backdrop (and the backdrop log file)

[Unit]
Description=backdrop wallpaper daemon
Documentation=https://github.com/njhoffman/backdrop
PartOf=graphical-session.target
After=graphical-session.target
# A daemon that cannot start (no X display, no monitors) gives up instead of retrying forever
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
ExecStart=${node} ${quote(this.entryPoint)} daemon
${environment}# backdrop stop exits cleanly, so a deliberate stop is not restarted
Restart=on-failure
RestartSec=5

[Install]
WantedBy=graphical-session.target
`;
  }

  print(version) {
    process.stdout.write(this.generate(version));
  }
}
